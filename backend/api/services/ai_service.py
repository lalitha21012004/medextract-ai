from google import genai
from django.conf import settings
import os
from google.genai.errors import APIError

PRIMARY_MODEL = "gemini-2.5-flash"  # Updated to stable current model identifier
FALLBACK_MODELS = ["gemini-2.5-flash-lite"]

def get_gemini_client():
    """Initializes and returns the Google GenAI Client."""
    api_key = getattr(settings, "GEMINI_API_KEY", None) or os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY is not configured in Django settings")
    return genai.Client(api_key=api_key)

def generate_with_fallback(client, prompt):
    """Tries generating content with primary model and fallbacks."""
    models_to_try = [PRIMARY_MODEL] + FALLBACK_MODELS
    for model_name in models_to_try:
        try:
            response = client.models.generate_content(
                model=model_name,
                contents=prompt,
            )
            return response.text
        except APIError as e:
            if getattr(e, 'code', None) == 503 or "UNAVAILABLE" in str(e):
                continue
            raise e
        except Exception as e:
            # Catch general generation exceptions and try fallback
            continue
    raise RuntimeError("All configured Gemini models are currently high demand. Try again later.")

def generate_medical_summary(parameters_data):
    """Takes extracted lab parameters and generates a plain-English summary."""
    client = get_gemini_client()

    param_text = "\n".join([
        f"- {p.get('parameter_name')}: {p.get('observed_value')} {p.get('unit')}"
        f" -(Reference: {p.get('reference_range')}, Status: {p.get('risk_level')})"
        for p in parameters_data
    ]) if parameters_data else "no specific parameters extracted"

    prompt = f"""You are an expert, compassionate medical assistant AI.
Analyze the following lab test parameters extracted from a medical report:
{param_text}

Provide a concise, patient-friendly response using standard Markdown with the following structured sections:
1. **Key Findings Summary**: A brief 2-3 sentence overview of the patient's health indicators.
2. **Detailed Parameter Analysis**: Explain any high or abnormal parameters in simple terms without causing panic.
3. **Lifestyle & Health Recommendations**: Practical diet, exercise, or lifestyle suggestions tailored to these results.
4. **Questions for Your Doctor**: 2-3 specific questions the patient can ask their physician during their next visit.

Disclaimer: This summary is generated by AI for informational purposes and does not replace a clinical diagnosis by a licensed healthcare professional."""
    
    return generate_with_fallback(client, prompt)

def answer_patient_question(parameters_data, user_question):
    """Answers follow-up patient questions grounded strictly in their lab parameters."""
    client = get_gemini_client()
    param_text = "\n".join([
        f"-{p.get('parameter_name')}:{p.get('observed_value')} {p.get('unit')} "
        f"(Reference :{p.get('reference_range')}, Status:{p.get('risk_level')})"
        for p in parameters_data
    ]) if parameters_data else "no specific parameters extracted."

    prompt = f"""
    You are a compassionate medical lab report assistant.
    Explain the following test results to a non-medical patient: {param_text}

    Patient Question: {user_question}

    Formatting Instructions:
    1. Use simple, non-jargon language.
    2. Format key medical findings using clear headings (e.g., ### 1. Key Finding).
    3. Use bullet points for list items.
    4. Highlight crucial metrics in **bold**.
    5. Always conclude with a brief, reassuring "Next Steps" section.
    """
    return generate_with_fallback(client, prompt)